import assert from "node:assert/strict";
import { readFileSync, writeFileSync } from "node:fs";

const contract = JSON.parse(readFileSync(new URL("../contracts/partner-v1.json", import.meta.url)));
const names = Object.keys(contract.components.schemas);
const supported = new Set([
  "$ref",
  "type",
  "properties",
  "required",
  "additionalProperties",
  "items",
  "prefixItems",
  "oneOf",
  "anyOf",
  "allOf",
  "enum",
  "const",
  "pattern",
  "minimum",
  "maximum",
  "minLength",
  "maxLength",
  "minItems",
  "maxItems",
  "uniqueItems",
  "propertyNames",
  "maxProperties",
  "format",
  "description",
  "title",
  "default",
  "discriminator",
  "examples",
  "example",
]);

function typeOf(schema) {
  if (schema === false) {
    return "never";
  }
  if (schema === true) {
    return "unknown";
  }
  for (const key of Object.keys(schema)) {
    assert(supported.has(key), `Unsupported schema keyword ${key}`);
  }
  if (schema.$ref) {
    const name = schema.$ref.replace("#/components/schemas/", "");
    assert(names.includes(name), "Unknown reference");
    return name;
  }
  if ("const" in schema) {
    return JSON.stringify(schema.const);
  }
  if (schema.enum) {
    return schema.enum.map((value) => JSON.stringify(value)).join(" | ");
  }
  for (const key of ["oneOf", "anyOf", "allOf"]) {
    if (schema[key]) {
      return `(${schema[key].map(typeOf).join(key === "allOf" ? " & " : " | ")})`;
    }
  }
  if (Array.isArray(schema.type)) {
    return schema.type.map((type) => typeOf({ ...schema, type })).join(" | ");
  }
  switch (schema.type) {
    case "null":
      return "null";
    case "boolean":
      return "boolean";
    case "number":
    case "integer":
      return "number";
    case "string":
      return "string";
    case "array":
      if (schema.prefixItems) {
        assert.equal(schema.items, false, "Open tuples require generator support");
        return `[${schema.prefixItems.map(typeOf).join(", ")}]`;
      }
      return `Array<${typeOf(schema.items ?? true)}>`;
    case "object": {
      const fields = Object.entries(schema.properties ?? {}).map(
        ([key, value]) =>
          `${JSON.stringify(key)}${schema.required?.includes(key) ? "" : "?"}: ${typeOf(value)};`,
      );
      if (schema.additionalProperties !== false) {
        fields.push(`[key: string]: ${typeOf(schema.additionalProperties ?? true)};`);
      }
      return `{ ${fields.join(" ")} }`;
    }
    default:
      throw new Error("Unsupported untyped schema");
  }
}

const lines = [
  "// Generated by scripts/generate.mjs from contracts/partner-v1.json. Do not edit.",
  'import type { Schema } from "./schema.ts";',
  ...names.map((name) => `export type ${name} = ${typeOf(contract.components.schemas[name])};`),
];
const responses = {
  presales: "PresalesResponse",
  featured: "FeaturedPresalesResponse",
  presale: "PresaleResponse",
  prices: "PricesReadResponse",
  search: "SearchReadResponse",
  status: "MarketStatusResponse",
};
const queries = {};
for (const [name, operation] of Object.entries(contract.operations)) {
  lines.push(`export type ${responses[name]} = ${typeOf(operation.schema)};`);
  const parameters = operation.parameters.filter((p) => p.in === "query");
  const schema = {
    type: "object",
    properties: Object.fromEntries(parameters.map((p) => [p.name, p.schema])),
    required: parameters.filter((p) => p.required).map((p) => p.name),
    additionalProperties: false,
  };
  queries[name] = schema;
  lines.push(`export type ${name[0].toUpperCase() + name.slice(1)}Query = ${typeOf(schema)};`);
}
lines.push(
  `export const schemas: Record<string, Schema> = ${JSON.stringify(contract.components.schemas)};`,
);
lines.push(
  `export const operations: Record<string, { path: string; schema: Schema }> = ${JSON.stringify(Object.fromEntries(Object.entries(contract.operations).map(([name, { path, schema }]) => [name, { path, schema }])))};`,
);
lines.push(`export const querySchemas: Record<string, Schema> = ${JSON.stringify(queries)};`);
const output = `${lines.join("\n\n")}\n`;
const path = new URL("../src/generated.ts", import.meta.url);
if (process.argv.includes("--check")) {
  assert.equal(
    readFileSync(path, "utf8"),
    output,
    "Generated contract is stale; run npm run generate",
  );
} else {
  writeFileSync(path, output);
}
